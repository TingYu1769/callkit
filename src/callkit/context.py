"""Context variables used to pass information between the scheduler and the recording layer.

Before running an item, the scheduler sets ``CURRENT_ITEM``; calls made through the recording client and ``Client`` in the same thread (or the same asyncio task) read it, write item_id and repeat into the record, and record the call IDs back. The thread pool sets it in worker threads; the async version sets it in each task, so they do not mix.
"""

from __future__ import annotations

from contextvars import ContextVar
from dataclasses import dataclass, field


@dataclass
class ItemContext:
    item_id: str
    repeat: int
    call_ids: list[str] = field(default_factory=list)  # Call IDs generated by this item.


CURRENT_ITEM: ContextVar[ItemContext | None] = ContextVar("callkit_item", default=None)
